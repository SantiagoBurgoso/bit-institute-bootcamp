// OPERADORES DE COMPARACION

// Ejemplo 1: Verificando la edad de un usuario (Igualdad estricta ===)
let userAge = 23;
let requiredAge = 23;
let hasExactAge = userAge === requiredAge; // true, porque ambos valores y tipos son iguales
console.log('Does the user have the exact required age?:', hasExactAge);

// Ejemplo 2: Validando el cilindraje de un vehiculo (Mayor o igual >=)
let motorcycleCc = 450;
let minimumCc = 400;
let canEnterTrack = motorcycleCc >= minimumCc;
console.log('Can enter the track?:', canEnterTrack);